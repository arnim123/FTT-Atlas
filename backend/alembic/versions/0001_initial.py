SEARCH_VECTOR_FUNCTION = """
CREATE OR REPLACE FUNCTION refresh_search_vector(p_document_id uuid)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_name text;
    v_description text;
    v_content text;
    v_category text;
    v_tags text;
    v_vector tsvector;
BEGIN
    SELECT d.name, d.description, d.content_text, c.name
      INTO v_name, v_description, v_content, v_category
    FROM documents AS d
    LEFT JOIN categories AS c ON c.id = d.category_id
    WHERE d.id = p_document_id;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT coalesce(string_agg(t.name, ' ' ORDER BY t.name), '')
      INTO v_tags
    FROM document_tags AS dt
    JOIN tags AS t ON t.id = dt.tag_id
    WHERE dt.document_id = p_document_id;

    v_vector :=
        setweight(to_tsvector('english', coalesce(v_name, '')), 'A') ||
        setweight(to_tsvector('english', concat_ws(' ', nullif(v_tags, ''), v_category)), 'B') ||
        setweight(to_tsvector('english', coalesce(v_description, '')), 'C') ||
        setweight(to_tsvector('english', coalesce(v_content, '')), 'D');

    UPDATE documents
       SET search_vector = v_vector
     WHERE id = p_document_id
       AND search_vector IS DISTINCT FROM v_vector;
END;
$$;
"""

